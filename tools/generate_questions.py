def main():
    fill_upper_common()
    all_questions = []
    for age in range(5, 11):
        rng = random.Random(20261103 + age)
        generated = build_math(age, rng)
        band = "5-6" if age <= 6 else ("7-8" if age <= 8 else "9-10")
        common = COMMON[band]
        assert len(generated) == 240, (age, len(generated))
        assert len(common) == 60, (band, len(common))
        for index, (category, prompt, correct, distractors, explanation) in enumerate(generated + common, 1):
            options = distractors + [correct]
            rng.shuffle(options)
            # Normalise accidental template labels before validation.
            options = [x.replace("", "") for x in options]
            all_questions.append({
                "id": f"a{age}-{index:04d}",
                "age": age,
                "category": category,
                "question": prompt,
                "options": options,
                "answerIndex": options.index(correct),
                "explanation": explanation,
            })

    ids = set()
    prompts = set()
    counts = {age: 0 for age in range(5, 11)}
    for q in all_questions:
        assert q["id"] not in ids
        assert (q["age"], q["question"]) not in prompts
        assert len(q["options"]) == 4
        assert len(set(q["options"])) == 4, q
        assert 0 <= q["answerIndex"] < 4
        assert q["question"].strip() and q["explanation"].strip()
        ids.add(q["id"])
        prompts.add((q["age"], q["question"]))
        counts[q["age"]] += 1
    assert len(all_questions) == 1800
    assert all(count >= 300 for count in counts.values())
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"version": 1, "questions": all_questions}, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(json.dumps({"total": len(all_questions), "perAge": counts, "file": str(OUT)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
