from __future__ import annotations
import random
from math import gcd


def _num_opts(ans: int | float, rng: random.Random, deltas=(-10, -4, -3, -2, -1, 1, 2, 3, 4, 10), allow_neg=False, suffix="") -> list[str]:
    cand = list(deltas)
    rng.shuffle(cand)
    out = []
    ans_s = f"{ans}{suffix}"
    for d in cand:
        v = round(ans + d, 2) if isinstance(ans, float) else ans + d
        if not allow_neg and v < 0:
            continue
        s = f"{v}{suffix}"
        if s != ans_s and s not in out:
            out.append(s)
        if len(out) == 3:
            return out
    step = 5
    while len(out) < 3:
        v = round(ans + step, 2) if isinstance(ans, float) else ans + step
        s = f"{v}{suffix}"
        if s != ans_s and s not in out:
            out.append(s)
        step += 2
    return out


def _frac_str(n: int, d: int) -> str:
    g = gcd(abs(n), abs(d))
    n //= g
    d //= g
    if d < 0:
        n, d = -n, -d
    return str(n) if d == 1 else f"{n}/{d}"


