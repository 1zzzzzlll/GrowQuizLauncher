        for week in range(1, 19):
            items: list[tuple] = []
            # 按年级 + 上下册 + 周次递进难度
            prog = week / 18.0
            if grade == 1:
                if term == "fall":
                    hi = 10 if week <= 8 else 20
                    a = rng.randint(2 if week <= 8 else 6, max(5, hi - 3))
                    b = rng.randint(2, min(9, hi - a + (4 if week > 12 else 0)))
