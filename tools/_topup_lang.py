# ---- merge ----------------------------------------------------------------
def table_block(name):
    """Return (start, end) slice of the table's text block in src."""
    m2 = re.search(rf"(?ms)^{name} = \[\n(.*?)^\]", src)
    assert m2, name
    return m2


existing_keys = {
    name: {x[0] for x in getattr(m, name)} for name in ADD
}
lines = {name: [] for name in ADD}
for name, cands in ADD.items():
    have = existing_keys[name]
    for t in cands:
        if t[0] not in have:
            have.add(t[0])
            body = ", ".join(f'"{x}"' for x in t)
            lines[name].append(f"    ({body}),")

for name, new_lines in lines.items():
    if not new_lines:
        continue
    block = table_block(name)
    insert = "\n".join(new_lines) + "\n"
    src = src[:block.end(1)] + ("" if block.group(1).endswith("\n") or not block.group(1) else "") + insert + src[block.end(1):]

P.write_text(src, encoding="utf-8")

